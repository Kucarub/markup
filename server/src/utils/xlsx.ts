/** 生成单 sheet 的 xlsx 文件内容 */
export function buildXlsx(
  sheetName: string,
  columns: XlsxColumn[],
  rows: Record<string, CellValue>[],
): Buffer {
  const safeSheetName = sheetName.replace(/[\\/?*[\]:]/g, ' ').slice(0, 31) || 'Sheet1'

  const cols = columns
    .map((column, index) => {
      const width = column.width ?? 16
      return `<col min="${index + 1}" max="${index + 1}" width="${width}" customWidth="1"/>`
    })
    .join('')

  const headerRow = `<row r="1">${columns
    .map((column, index) => buildCell(`${columnLetter(index)}1`, column.title, 1))
    .join('')}</row>`

  const dataRows = rows
    .map((row, rowIndex) => {
      const line = rowIndex + 2
      const cells = columns
        .map((column, colIndex) =>
          buildCell(`${columnLetter(colIndex)}${line}`, row[column.key], 0),
        )
        .join('')
      return `<row r="${line}">${cells}</row>`
    })
    .join('')

  const worksheet = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>
<cols>${cols}</cols>
<sheetData>${headerRow}${dataRows}</sheetData>
</worksheet>`

  const workbook = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheets><sheet name="${escapeXml(safeSheetName)}" sheetId="1" r:id="rId1"/></sheets>
</workbook>`

  return zip([
    { name: '[Content_Types].xml', data: Buffer.from(CONTENT_TYPES, 'utf8') },
    { name: '_rels/.rels', data: Buffer.from(ROOT_RELS, 'utf8') },
    { name: 'xl/workbook.xml', data: Buffer.from(workbook, 'utf8') },
    { name: 'xl/_rels/workbook.xml.rels', data: Buffer.from(WORKBOOK_RELS, 'utf8') },
    { name: 'xl/styles.xml', data: Buffer.from(STYLES, 'utf8') },
    { name: 'xl/worksheets/sheet1.xml', data: Buffer.from(worksheet, 'utf8') },
  ])
}
